/* ============================================================
 * @file drv.h
 * @brief 设备驱动接口声明
 *
 * 层级：
 *   TurboBoxOS/drv/
 *
 * 项目内绝对路径：
 *   TurboBoxOS/drv/drv.h
 *
 * 模块作用：
 *   对外提供 VGA 文本输出与 PS/2 键盘输入的字符设备接口。
 *   上层只看到 putc/puts/getc 这类字符语义，不需要知道显存地址
 *   和端口 IO 细节，便于以后替换成帧缓冲或串口输出。
 *
 * 使用者：
 *   kernel、user、middle 等模块通过本文件调用驱动。
 *
 * 项目角色：
 *   drv 层的对外接口头，是驱动层与上层之间的唯一约定。
 *
 * 引入说明：
 *   不依赖其他头文件，纯函数声明。
 *
 * 维护记录：
 *   2026-08-30 初始创建
 * ============================================================ */

#ifndef TURBOX_DRV_DRV_H
#define TURBOX_DRV_DRV_H

/*
 * 初始化 VGA 文本模式。
 * 清屏并把光标归零，所有 VGA 输出前必须先调用一次。
 */
void vga_init();

/*
 * 输出一个字符，支持 '\n' 换行和自动滚屏。
 * 传 '\0' 不会输出也不会移动光标。
 */
void vga_putc(char c);

/*
 * 输出以 '\0' 结尾的字符串。
 * 内部逐个调用 vga_putc，所以换行和滚屏规则一致。
 */
void vga_puts(const char* s);

/*
 * 初始化键盘控制器，清空输出缓冲区。
 * 启动时残留的扫描码会影响第一次读取，所以要先丢弃。
 */
void kbd_init();

/*
 * 阻塞读取一个按键，扫描码集 1。
 * 目前支持小写字母、数字、空格、回车 '\n'、退格 '\b'。
 * 没有按键时会一直轮询 IO 端口，不会返回。
 */
char kbd_getc();

#endif /* TURBOX_DRV_DRV_H */