; ============================================================
; @file loader.asm
; @brief 引导第二段，开启保护模式并交接 C++ 内核
;
; 层级：
;   TurboBoxOS/boot/
;
; 项目内绝对路径：
;   TurboBoxOS/boot/loader.asm
;
; 模块作用：
;   由 boot.asm 远跳转进入。负责开启 A20、加载 GDT、切换到
;   32 位保护模式，最后跳入 C++ 的 kernel_main。
;
; 使用者：
;   boot.asm 跳转进入本模块，本模块再跳入 kernel/kernel.cpp。
;
; 项目角色：
;   启动第二环，完成实模式到保护模式的最后交接。
;
; 引入说明：
;   依赖 boot.asm 设置好的 0x10000 加载地址。
;   需要 C++ 侧提供 extern "C" 的 kernel_main 符号。
;
; 维护记录：
;   2026-08-30 初始创建
; ============================================================

BITS 16
ORG 0x0000                  ; 本文件被 boot.asm 远跳转到 0x1000:0x0000 执行，偏移从 0 开始

extern kernel_main          ; C++ 内核入口，位于 kernel/kernel.cpp

start:
    cli                     ; 模式切换期间禁止 BIOS 中断，避免破坏 CPU 状态

; ------------------------------------------------------------
; 开启 A20 地址线
; A20 默认被禁用是为了兼容旧的 8086 回绕行为；
; 不开启则地址超过 1MB 后会被截断，C++ 内核无法使用完整内存
; 这里采用快速 A20 门（端口 0x92），兼容性好，不需要 BIOS 中断
; ------------------------------------------------------------
    in   al, 0x92
    or   al, 00000010b      ; 置 bit1：开启 A20
    and  al, 11111110b      ; 清 bit0：避免触发系统复位
    out  0x92, al

; ------------------------------------------------------------
; 加载 GDT
; 保护模式下的段寻址依赖全局描述符表，必须在进入保护模式前设置好
; ------------------------------------------------------------
    lgdt [gdt_desc]

; ------------------------------------------------------------
; 进入保护模式
; 将 CR0 的 PE 位（bit0）置 1，CPU 随即按保护模式规则运行
; ------------------------------------------------------------
    mov  eax, cr0
    or   eax, 1
    mov  cr0, eax

    ; 远跳转刷新流水线，加载代码段选择子 0x08
    ; 0x08 的二进制为 1000b：
    ;   TI=0 使用 GDT，RPL=0 内核级，索引=1 对应 GDT 第 1 项（代码段）
    jmp  0x08:protected_mode

BITS 32
protected_mode:
    ; 0x10 的二进制为 10000b：
    ;   TI=0 使用 GDT，RPL=0，索引=2 对应 GDT 第 2 项（数据段）
    mov  ax, 0x10
    mov  ds, ax
    mov  es, ax
    mov  fs, ax
    mov  gs, ax
    mov  ss, ax

    ; 内核栈放在 0x90000，远离 0x10000 加载区和 0x7C00 引导区
    ; 0x90000 位于低 1MB 内，栈向下生长，不会与低地址数据冲突
    mov  esp, 0x90000

    call kernel_main        ; 正式进入 C++ 微内核

.hang:
    cli
    hlt                     ; kernel_main 不应返回；返回说明内核已崩，停机保护
    jmp  .hang

; ------------------------------------------------------------
; GDT 表：空描述符 + 代码段描述符 + 数据段描述符
; 三者都采用平坦模型：基址 0，限界 4GB
; ------------------------------------------------------------
gdt_start:
    ; 第 0 项：空描述符，CPU 强制要求，不可用
    dq 0x0000000000000000

    ; 第 1 项：代码段描述符
    ; 属性：基址 0，限界 4GB，可执行可读，非系统段，DPL=0，32 位保护模式
    dq 0x00CF9A000000FFFF

    ; 第 2 项：数据段描述符
    ; 属性：基址 0，限界 4GB，可读写，非系统段，DPL=0，32 位保护模式
    dq 0x00CF92000000FFFF
gdt_end:

gdt_desc:
    ; GDT 限界 = 表总字节数 - 1
    dw gdt_end - gdt_start - 1

    ; GDT 物理基址 = loader 加载基址 0x10000 + 表在段内偏移
    ; 注意：不能直接写 gdt_start，因为 CPU 需要的是线性物理地址
    dd 0x10000 + gdt_start

; loader 单独占一个扇区，方便与内核按扇区对齐链接
times 512 - ($ - $$) db 0